// Package domesticip resolves the direct Caddy client and applies a pinned
// domestic-network snapshot without trusting the legacy forwarding headers.
package domesticip

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"strings"
	"time"
)

const maxSnapshotBytes = 16 << 20

var (
	ErrInvalidPublicIP    = errors.New("当前网络取不到公网 IP，请切换网络后重试")
	ErrUntrustedPeer      = errors.New("domestic IP policy requires the trusted local proxy")
	ErrInvalidForwardedIP = errors.New("domestic IP policy requires one public forwarded address")
)

type Options struct {
	Enabled         bool
	SnapshotFile    string
	SnapshotSHA256  string
	TrustedProxyIPs []string
}

// Snapshot is shared with the Caddy include generated by export_policy.py.
// GeneratedAt is provenance, not an expiration date.
type Snapshot struct {
	Version     int      `json:"version"`
	GeneratedAt string   `json:"generated_at"`
	CNCIDRs     []string `json:"cn_cidrs"`
	ManualIPs   []string `json:"manual_ips"`
}

type prefixIndex struct {
	prefixes map[netip.Prefix]struct{}
	lengths4 []int
	lengths6 []int
}

func newPrefixIndex(prefixes []netip.Prefix) prefixIndex {
	x := prefixIndex{prefixes: make(map[netip.Prefix]struct{}, len(prefixes))}
	lengths4, lengths6 := map[int]bool{}, map[int]bool{}
	for _, p := range prefixes {
		x.prefixes[p] = struct{}{}
		if p.Addr().Is4() {
			lengths4[p.Bits()] = true
		} else {
			lengths6[p.Bits()] = true
		}
	}
	for n := range lengths4 {
		x.lengths4 = append(x.lengths4, n)
	}
	for n := range lengths6 {
		x.lengths6 = append(x.lengths6, n)
	}
	sort.Sort(sort.Reverse(sort.IntSlice(x.lengths4)))
	sort.Sort(sort.Reverse(sort.IntSlice(x.lengths6)))
	return x
}

func (x prefixIndex) contains(addr netip.Addr) bool {
	lengths := x.lengths6
	if addr.Is4() {
		lengths = x.lengths4
	}
	for _, bits := range lengths {
		if _, ok := x.prefixes[netip.PrefixFrom(addr, bits).Masked()]; ok {
			return true
		}
	}
	return false
}

type Policy struct {
	enabled bool
	digest  string
	cn      prefixIndex
	manual  map[netip.Addr]struct{}
	proxies map[netip.Addr]struct{}
}

func NewPolicy(options Options) (*Policy, error) {
	p := &Policy{enabled: options.Enabled, manual: map[netip.Addr]struct{}{}, proxies: map[netip.Addr]struct{}{}}
	if !options.Enabled {
		return p, nil
	}
	proxies := options.TrustedProxyIPs
	if len(proxies) == 0 {
		proxies = []string{"127.0.0.1", "::1"}
	}
	for _, raw := range proxies {
		addr, err := netip.ParseAddr(strings.TrimSpace(raw))
		if err != nil || addr.Zone() != "" || !addr.IsLoopback() {
			return nil, errors.New("domestic IP trusted proxies must be exact loopback IP addresses")
		}
		p.proxies[addr.Unmap()] = struct{}{}
	}
	expected, err := hex.DecodeString(options.SnapshotSHA256)
	if err != nil || len(expected) != sha256.Size {
		return nil, errors.New("domestic IP policy requires a pinned SHA-256")
	}
	file, err := os.Open(options.SnapshotFile)
	if err != nil {
		return nil, errors.New("cannot open domestic IP policy snapshot")
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, maxSnapshotBytes+1))
	if err != nil || len(data) > maxSnapshotBytes {
		return nil, errors.New("cannot read domestic IP policy snapshot within size limit")
	}
	digest := sha256.Sum256(data)
	if !bytes.Equal(digest[:], expected) {
		return nil, errors.New("domestic IP policy snapshot SHA-256 mismatch")
	}
	snapshot, err := ValidateSnapshot(data)
	if err != nil {
		return nil, err
	}
	p.digest = hex.EncodeToString(digest[:])
	prefixes := make([]netip.Prefix, 0, len(snapshot.CNCIDRs))
	for _, raw := range snapshot.CNCIDRs {
		prefixes = append(prefixes, netip.MustParsePrefix(raw))
	}
	p.cn = newPrefixIndex(prefixes)
	for _, raw := range snapshot.ManualIPs {
		p.manual[netip.MustParseAddr(raw).Unmap()] = struct{}{}
	}
	return p, nil
}

// ValidateSnapshot rejects ambiguous, empty, broad or non-public policy data.
// Errors contain indexes, never operational IP addresses.
func ValidateSnapshot(data []byte) (*Snapshot, error) {
	if len(data) > maxSnapshotBytes {
		return nil, errors.New("domestic IP policy snapshot exceeds size limit")
	}
	var snapshot Snapshot
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&snapshot); err != nil {
		return nil, errors.New("invalid domestic IP policy JSON")
	}
	if err := decoder.Decode(new(any)); !errors.Is(err, io.EOF) {
		return nil, errors.New("trailing domestic IP policy JSON")
	}
	if snapshot.Version != 1 {
		return nil, errors.New("unsupported domestic IP policy version")
	}
	if _, err := time.Parse(time.RFC3339, snapshot.GeneratedAt); err != nil {
		return nil, errors.New("invalid domestic IP policy generation time")
	}
	if len(snapshot.CNCIDRs) > 100000 || len(snapshot.ManualIPs) > 100000 {
		return nil, errors.New("domestic IP policy has too many entries")
	}
	seen := map[netip.Prefix]bool{}
	has4, has6 := false, false
	for i, raw := range snapshot.CNCIDRs {
		prefix, err := netip.ParsePrefix(raw)
		if err != nil || prefix.Addr().Is4In6() || prefix != prefix.Masked() || prefix.String() != raw {
			return nil, fmt.Errorf("invalid domestic CIDR at index %d", i)
		}
		if !isPublicAddr(prefix.Addr()) {
			return nil, fmt.Errorf("non-public domestic CIDR at index %d", i)
		}
		for _, denied := range excludedPrefixes {
			if prefix.Overlaps(denied) {
				return nil, fmt.Errorf("reserved overlap in domestic CIDR at index %d", i)
			}
		}
		if prefix.Addr().Is6() && !netip.MustParsePrefix("2000::/3").Contains(prefix.Addr()) {
			return nil, fmt.Errorf("non-global domestic CIDR at index %d", i)
		}
		if seen[prefix] {
			return nil, fmt.Errorf("duplicate domestic CIDR at index %d", i)
		}
		seen[prefix] = true
		if prefix.Addr().Is4() {
			has4 = true
		} else {
			has6 = true
		}
	}
	if !has4 || !has6 {
		return nil, errors.New("domestic IP snapshot must contain both IPv4 and IPv6 ranges")
	}
	manualSeen := map[string]bool{}
	for i, raw := range snapshot.ManualIPs {
		normalized, err := NormalizePublicIP(raw)
		if err != nil || normalized != raw || manualSeen[normalized] {
			return nil, fmt.Errorf("invalid manual IP at index %d", i)
		}
		manualSeen[normalized] = true
	}
	return &snapshot, nil
}

func (p *Policy) Enabled() bool { return p != nil && p.enabled }
func (p *Policy) SnapshotSHA256() string {
	if p == nil {
		return ""
	}
	return p.digest
}

// ResolveClientIP accepts only a direct configured Caddy peer and one XFF
// value. CF-Connecting-IP, X-Real-IP and the legacy Gin trust setting are ignored.
// Caddy must overwrite XFF; app port binding must independently exclude public
// peers. Restricting this function alone does not secure other app IP consumers.
func (p *Policy) ResolveClientIP(r *http.Request) (string, error) {
	if p == nil || !p.enabled || r == nil {
		return "", ErrUntrustedPeer
	}
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		return "", ErrUntrustedPeer
	}
	peer, err := netip.ParseAddr(host)
	if err != nil || peer.Zone() != "" {
		return "", ErrUntrustedPeer
	}
	if _, ok := p.proxies[peer.Unmap()]; !ok {
		return "", ErrUntrustedPeer
	}
	values := r.Header.Values("X-Forwarded-For")
	if len(values) != 1 {
		return "", ErrInvalidForwardedIP
	}
	addr, err := NormalizePublicIP(values[0])
	if err != nil {
		return "", ErrInvalidForwardedIP
	}
	return addr, nil
}

func (p *Policy) IsDomestic(raw string) bool {
	if !p.Enabled() {
		return false
	}
	addr, err := netip.ParseAddr(raw)
	return err == nil && p.cn.contains(addr.Unmap())
}

func (p *Policy) IsManualAllowed(raw string) bool {
	if !p.Enabled() {
		return false
	}
	addr, err := netip.ParseAddr(raw)
	if err != nil {
		return false
	}
	_, found := p.manual[addr.Unmap()]
	return found
}

func (p *Policy) NeedsGrant(r *http.Request) (string, bool, error) {
	if !p.Enabled() {
		return "", false, nil
	}
	addr, err := p.ResolveClientIP(r)
	if err != nil {
		return "", false, err
	}
	return addr, p.IsDomestic(addr) && !p.IsManualAllowed(addr), nil
}
